static void load_font() {
    for (int g = 0; g < 96; ++g) {
        TILE *tile = &tile_mem[0][g];
        for (int y = 0; y < 8; ++y) {
            unsigned bits = font8x8[g][y];
            u32 row = 0;
            for (int x = 0; x < 8; ++x) {
                if (bits & (1u << x)) {
                    row |= 1u << ((7 - x) * 4);
                }
            }
            tile->data[y] = row;
        }
    }
}

void logo_init(void) {
    REG_DISPCNT = DCNT_MODE0 | DCNT_BG0;
    REG_BG0CNT = BG_CBB(0) | BG_SBB(31) | BG_4BPP;
    REG_BG0HOFS = 0;
    REG_BG0VOFS = 0;
    pal_bg_mem[0] = RGB15(0, 0, 0);
    pal_bg_mem[1] = RGB15(31, 31, 31);
    load_font();
    for (int i = 0; i < 32 * 20; ++i) {
        se_mem[31][i] = 0;
    }
    logo_x = 0;
    logo_y = 0;
}

void logo(const char *s) {
    while (*s) {
        char c = *s++;
        if (c == '\n' || logo_x >= 30) {
            logo_x = 0;
            if (logo_y < 19) {
                ++logo_y;
            }
            if (c == '\n') {
                continue;
            }
        }
        if (c < 32) {
            continue;
        }
        int g = (unsigned char)c - 32;
        if (g > 95) {
            g = 0;
        }
        se_mem[31][logo_y * 32 + logo_x] = (SCR_ENTRY)g;
        ++logo_x;
    }
}

void logo_i(const char *s, int n) {
    char buf[12];
    char *p = buf + 11;
    unsigned u = n < 0 ? (unsigned)(-n) : (unsigned)n;

    *p = '\0';
    do {
        *--p = static_cast<char>('0' + (u % 10));
        u /= 10;
    } while (u);
    if (n < 0) {
        *--p = '-';
    }

    logo(s);
    logo(p);
    logo("\n");
}

void logo_gas(int cur, int all) {
    if (gas_x < 0) {
        if (logo_x != 0) {
            logo("\n");
        }
        gas_x = 0;
        gas_y = logo_y;
    }

    int width = 30 - gas_x;
    if (width < 4) {
        width = 30;
        gas_x = 0;
        if (gas_y < 19) {
            ++gas_y;
        }
    }

    int inner = width - 2;
    int fill = 0;
    if (all > 0) {
        fill = inner * cur / all;
    }
    if (fill > inner) {
        fill = inner;
    }
    if (fill < 0) {
        fill = 0;
    }

    logo_x = gas_x;
    logo_y = gas_y;
    logo("[");
    for (int i = 0; i < inner; ++i) {
        logo(i < fill ? "." : " ");
    }
    logo("]");
    logo_x = gas_x;
    logo_y = gas_y;
    if (all > 0 && cur >= all) {
        gas_x = -1;
    }
}
